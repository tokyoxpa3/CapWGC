// ============================================================================
// autostart.h — 開機自動啟動（HKCU\Software\Microsoft\Windows\CurrentVersion\Run）
// ============================================================================
//
// 只寫「目前使用者」的 Run 機碼，不碰 HKLM：不需要系統管理員權限，停用時也只
// 移除自己那一個值，不會影響其他程式或別人的帳號。
//
// ---- 為什麼要獨立成一個模組 ------------------------------------------------
//
// 「目前執行中的 exe 是哪一個」這個問題，在這個專案裡看起來很無聊（一支 C++
// exe，GetModuleFileNameW 不就結了？），但它正是參考實作
// （D:\workspace\MultiSocksDownloader）踩過坑的地方，而且那個坑很容易複製：
//
//   那邊是 Python，打包後（Nuitka standalone）`sys.executable` 指向 dist 內建
//   的 python.exe，真正的程式 exe 只有 `sys.argv[0]` 才拿得到；而且 Nuitka
//   不設 `sys.frozen`，要用模組層級的 `__compiled__` 判斷是不是打包版。所以
//   他們特地開了 runtime_env.py 當「唯一判斷來源」，理由寫得很直白：這個判斷
//   原本在五個模組各寫一份，其中一份漏改，打包版就被當成開發模式、整段功能
//   靜默跳過。
//
//   C++ 沒有那兩個坑（沒有內建解譯器、沒有「編譯過的模組」這回事），但**同一
//   類錯誤照樣會發生**：只要有人為了「知道自己是誰」去讀 GetCommandLineW()
//   或 CommandLineToArgvW()[0]，拿到的就不是 exe 路徑，而是「別人怎麼啟動
//   我」——從捷徑啟動是完整路徑、從 8.3 短名啟動是短名、被別的程式帶參數
//   啟動時甚至可能是相對路徑或別的東西。把它寫進註冊表，結果就是開機起不來
//   （路徑錯誤）或起錯程式（指到舊版本目錄的 exe），而且**完全無聲**：登入後
//   什麼都沒發生，使用者只會覺得「這軟體壞了」。
//
//   所以本模組的 exe 路徑**只有一個來源**：GetModuleFileNameW(nullptr)。
//   不要在這裡加第二種取法，也不要在呼叫端自己拼一份。
//
// ---- 「有值」不等於「已啟用」（三個都要分清楚）-----------------------------
//
//   NotSet   機碼裡沒有這個值 → 從沒設過，或使用者關掉了。
//   Enabled  有值，而且指的就是**現在這支 exe**。
//   Stale    有值但指向別的檔案（換版本目錄、開發版 out\ 與打包版 dist\ 互跑）
//            → 開機不會啟動我們。參考實作只檢查「那個檔案還在不在」，這裡
//            多比對路徑：檔案存在但不我們，勾選框會顯示成已啟用，而取消勾選
//            又會刪掉一個其實不是我們的項目。
//   Blocked  有值且指向我們，但被 Windows 的「啟動應用程式」停用了
//            （工作管理員 / 設定 → 應用程式 → 啟動）。這是「預設開啟」最典型
//            的翻車點：不認這個狀態的話，我們會在使用者明確停用之後，每次
//            啟動又把它寫回去。
// ============================================================================

#pragma once

#ifndef NOMINMAX
#define NOMINMAX

#endif

#include <string>

namespace app {
namespace autostart {

// 登錄值名稱。固定不變 —— 停用時要靠它精準移除「我們自己」寫的那一項。
extern const wchar_t* const kValueName;

enum class State { NotSet, Enabled, Stale, Blocked };

// 讀目前狀態。讀不到機碼（權限／被鎖）時回 NotSet —— 對使用者來說兩者都是
// 「沒有啟用」，而回錯誤只會讓呼叫端多一條走不到的分支。
State Query();

// 寫入 / 移除。回傳 false 只代表登錄檔寫不進去（群組原則、安全軟體）；呼叫端
// 要把原因講出來，不能只說「失敗」。
bool Enable();
bool Disable();

// ini 裡的「使用者已經對這件事做過決定」記號（[startup] chosen）。
//
// 為什麼需要它：預設開啟是在啟動時**主動寫註冊表**，而「ini 裡有沒有值」分不
// 出兩件事 ——
//   * 使用者從來沒碰過（升級上來的舊使用者）→ 應該套用預設（開）
//   * 使用者刻意關掉（ini 沒有值，因為我們把註冊表項刪了）→ 不該每次開機
//     又被翻回來
// 所以另外記一個「問過了」的記號：沒有它＝還沒問過，可以套預設。
bool Chosen();
void SetChosen(bool chosen);

// 啟動時呼叫一次：套用「預設開啟」，並修好換版本目錄造成的 Stale。
//
// 三種情況：
//   1. 沒問過 + NotSet/Stale  → 寫入（預設開啟）
//   2. 沒問過 + Blocked       → **不動**。那是使用者在 Windows 設定裡停用的，
//                                尊重它比貫徹預設值重要。
//   3. 問過了                → 只有 Stale 才修（那是升級換了目錄，不是他要關）。
void EnsureDefaultOn();

// 把「使用者要什麼」落實到註冊表。**副作用只有這一個入口。**
//
// 為什麼要抽出來：這段原本寫在 OpenSettings 裡，而 `--settings` 這條 QA 路徑
// （無頭開設定視窗、按確定、存檔）走的不是 OpenSettings 而是直接
// ShowSettingsDialog + Save —— 於是「勾了按確定會寫註冊表」這件事在自動化測試
// 裡**一行都沒被執行過**。實際踩到：測試回報 3 輪只有 1 輪過，看起來像功能壞
// 了，其實是測試繞過了實作。這正是參考實作那份註解的同一類錯誤 ——
// 「同一件副作用的實作散在幾個地方，其中一條路徑漏了」。
//
// 語意：
//   want == 目前的實際狀態 → 什麼都不做（不重寫，免得蓋掉使用者在登錄檔裡
//                            手動加的參數）
//   want == true           → 寫入，並記下「問過了」
//   want == false          → 移除，並記下「問過了」
//
// 回傳 false 只代表 want==true 時寫不進去（群組原則／安全軟體）。呼叫端要把
// 原因講出來，不能只說「失敗」。
bool Apply(bool want);

// 註冊表目前是不是「已啟用」（Enabled）。給 UI 顯示與變更偵測用。
bool IsEnabled();

// 要寫進註冊表的命令列（`"C:\...\CapWGC.exe"`，含引號）。
//
// 不含任何參數：開機啟動只要把托盤程式叫起來，不需要「開啟檔案」之類的
// 上下文，帶參數反而會讓某些 shell 把它當成檔案關聯的呼叫。
std::wstring Command();

// 目前執行中的 exe 完整路徑。空字串 = 取不到（理論上不會發生）。
std::wstring ExePath();

} // namespace autostart
} // namespace app
